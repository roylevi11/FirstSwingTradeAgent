"""
client_message_agent.py
========================
פיילוט מערכת רב-סוכנית (נושא 2, משימת בונוס - 3 נק', לא חובה).

סוכן א' (agent/loop.py, run_agent) = מנתח נתונים - מפיק תזכיר עסקה טכני.
סוכן ב' (כאן, humanize_memo) = כותב תקשורת ללקוח - מקבל את התזכיר
הטכני כקלט, והופך אותו להודעה קצרה, ברורה וידידותית, כאילו נשלחת
בוואטסאפ/טלגרם ללקוח שאינו בהכרח מבין מונחים טכניים.

זו העברה ידנית (הפלט של סוכן א' מודבק כקלט לסוכן ב') - בדיוק כפי
שהמטלה מבקשת להדגים, ולא אוטומציה מלאה בין סוכנים (שמעבר להיקף).
"""

import os

import anthropic

CLIENT_MESSAGE_SYSTEM_PROMPT = """\
אתה "סוכן ב'" - כותב תקשורת ללקוח. תפקידך היחיד הוא לקחת תזכיר עסקה
טכני (שכתב "סוכן א'", אנליסט) ולהפוך אותו להודעה קצרה (עד 4 משפטים),
ברורה, ידידותית - כאילו נשלחת הודעת וואטסאפ ללקוח שאינו בקיא במונחים
פיננסיים. אל תשנה שום מספר או עובדה מהתזכיר המקורי - רק נסח מחדש
בשפה פשוטה. אם התזכיר מדווח על דחיית עסקה, ההודעה צריכה להסביר בקצרה
ובנימוס למה, בלי לייאש. תמיד סיים בתזכורת שזו המלצה בלבד וההחלטה
הסופית בידי הלקוח.
"""


def humanize_memo(memo_text: str, api_key: str | None = None) -> str:
    """
    סוכן ב': מקבל את פלט סוכן א' (תזכיר טכני) כקלט, מחזיר הודעת לקוח.
    זוהי קריאת Claude API נפרדת, עם System Prompt שונה לגמרי - הדגמה
    מינימלית של "התמחות וחלוקת עבודה בין סוכנים".
    """
    client = anthropic.Anthropic(api_key=api_key or os.environ.get("ANTHROPIC_API_KEY"))
    response = client.messages.create(
        model="claude-haiku-4-5-20251001",  # משימה פשוטה - לא צריך את המודל היקר
        max_tokens=300,
        system=CLIENT_MESSAGE_SYSTEM_PROMPT,
        messages=[{"role": "user", "content": f"תזכיר מסוכן א':\n\n{memo_text}"}],
    )
    return "".join(block.text for block in response.content if block.type == "text")


if __name__ == "__main__":
    # דוגמה להרצה ידנית: מדביקים כאן תזכיר אמיתי שיצא מ-run_agent()
    example_memo = (
        "מניה: NVDA (NVIDIA Corp)\nסטטוס: נכשל / נדחה\n"
        "סיבות:\n  - יחס סיכון/סיכוי: 1:1.12 נמוך מהסף המינימלי הנדרש של 1:2.\n"
        "סיכום: העסקה אינה מאושרת לביצוע."
    )
    print(humanize_memo(example_memo))
